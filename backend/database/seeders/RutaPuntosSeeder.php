    public function run(): void
    {
        foreach (self::RUTAS_DETALLADAS as $codigoRuta => $rutaData) {
            $ruta = DB::table('rutas')->where('codigo', $codigoRuta)->first();

            if (!$ruta) {
                continue;
            }

            DB::table('ruta_puntos')->where('ruta_id', $ruta->id)->delete();

            $orden = 1;

            $inicio = $rutaData['inicio'];
            DB::table('ruta_puntos')->insert([
                'ruta_id' => $ruta->id,
                'orden' => $orden++,
                'latitud' => $inicio['lat'],
                'longitud' => $inicio['lng'],
                'nombre' => $inicio['nombre'] ?? null,
            ]);

            foreach ($rutaData['puntos'] as $punto) {
                DB::table('ruta_puntos')->insert([
                    'ruta_id' => $ruta->id,
                    'orden' => $orden++,
                    'latitud' => $punto['lat'],
                    'longitud' => $punto['lng'],
                    'nombre' => $punto['nombre'] ?? null,
                ]);
            }
        }
    }
